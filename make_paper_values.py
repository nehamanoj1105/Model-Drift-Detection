"""
make_paper_values.py — one-stop value sync.

Reads the saved final results (results/final/summary.json, tables/*.csv) and
prints every number used in the paper into paper_values.md. No number is typed
by hand; everything is derived from results files produced by the harness.

Run from the "Ensemble Learning for Model Drift Detection" directory:
    python make_paper_values.py
"""

import os
import sys
import json
import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
EXP = os.path.join(HERE, "Ensemble Learning for Model Drift Detection")
sys.path.insert(0, os.path.join(EXP, "experiments", "final"))
sys.path.insert(0, os.path.join(EXP, "experiments", "exp9a"))

RESULTS = os.path.join(EXP, "results", "final")
TABLES = os.path.join(RESULTS, "tables")
RAW = os.path.join(RESULTS, "raw")

LABEL = {"5g_campus": "5G Campus", "ugr16": "UGR'16",
         "nordicdat": "NordicDat", "5g_nr": "5G NR Lat."}


def _read(name):
    p = os.path.join(TABLES, name)
    return pd.read_csv(p) if os.path.exists(p) else None


def fmt(x, n=4):
    try:
        return f"{float(x):.{n}f}"
    except Exception:
        return str(x)


def main():
    out = []
    w = out.append
    w("# Paper values (auto-generated by make_paper_values.py)\n")
    w("Every value below is read from `results/final/`. Do not hand-edit.\n")

    summ_path = os.path.join(RESULTS, "summary.json")
    if not os.path.exists(summ_path):
        raise SystemExit("missing results/final/summary.json — run final_stats.py first")
    summ = json.load(open(summ_path))
    s = pd.DataFrame(summ["summary"])
    w(f"\n- Seeds: {summ['n_seeds']} (42-71)\n- TOST margin: +/-{summ['tost_margin']} macro-F1\n")

    # ---- Table I: dataset facts ----
    w("\n## Table I — datasets\n")
    try:
        from run_final import _prepare_stream
        facts = []
        for slug, name in [("5g_campus", "5G Campus QoS"), ("ugr16", "UGR'16"),
                           ("nordicdat", "NordicDat"), ("5g_nr", "5G NR Latency")]:
            _, sd = _prepare_stream(name)
            regs = pd.Series(sd["regime_sequence"])
            facts.append(dict(dataset=LABEL[slug],
                              raw_samples=sd["n_raw_samples"],
                              usable_samples=sd["n_usable_samples"],
                              features=len(sd["feature_columns"]),
                              classes=sd["n_classes"],
                              windows=sd["total_windows"],
                              window_size=sd["window_size"],
                              regimes=int(regs.nunique()),
                              initial_train_windows=sd["initial_train_windows"]))
        ft = pd.DataFrame(facts)
        ft.to_csv(os.path.join(TABLES, "table_datasets.csv"), index=False)
        w(ft.to_markdown(index=False))
    except Exception as e:
        w(f"(dataset facts unavailable: {e})")

    # ---- Table II: primary ----
    w("\n## Table II — primary comparison (mean over 30 seeds)\n")
    piv = s.pivot_table(index="method", columns="stream", values="macro_f1")
    w(piv.round(4).to_markdown())
    for col in piv.columns:
        best = piv[col].idxmax()
        w(f"- best macro-F1 on {col}: {best} = {fmt(piv.loc[best, col])}")

    # ---- cost savings ----
    w("\n## Cost vs Full Retraining (adaptation CPU)\n")
    for stream in s["stream"].unique():
        sub = s[s["stream"] == stream].set_index("method")
        if "Full Retraining" not in sub.index:
            continue
        base_a = sub.loc["Full Retraining", "adaptation_cpu_sec"]
        base_t = sub.loc["Full Retraining", "total_cpu_sec"]
        for m in ["RAPT", "RAPT-Enhanced", "RAPT-Guard", "RAPT-Anchor"]:
            if m in sub.index and base_a:
                sa = 100 * (1 - sub.loc[m, "adaptation_cpu_sec"] / base_a)
                rm = sub.loc[m, "retrains"]; ru = sub.loc[m, "reuses"]
                w(f"- {LABEL[stream]}: {m} adaptation CPU {fmt(sub.loc[m,'adaptation_cpu_sec'])} s "
                  f"({sa:+.1f}% vs Full {fmt(base_a)} s), total {fmt(sub.loc[m,'total_cpu_sec'])} s, "
                  f"retrains {rm:.1f}, reuses {ru:.1f}")

    # ---- statistics ----
    st = _read("statistics.csv")
    if st is not None:
        w("\n## Statistics (Wilcoxon+Holm, Cohen's dz, TOST +/-0.02)\n")
        for _, r in st.iterrows():
            if r["comparison"].startswith(("RAPT-Guard", "RAPT-Anchor")):
                w(f"- {LABEL.get(r['stream'], r['stream'])} {r['comparison']}: "
                  f"window p={r['window_p']:.2e} (Holm {r['window_p_holm']:.2e}), "
                  f"seed dz={r['seed_dz']:.2f}, t p={r['seed_t_p']:.3g}, "
                  f"TOST p={r['tost_p']:.3g}, d_mean={r['seed_mean_diff']:+.4f}")

    # ---- gate accuracy ----
    ga = _read("gate_accuracy.csv")
    if ga is not None:
        w("\n## RAPT-Guard gate accuracy\n")
        w(ga.to_markdown(index=False))

    # ---- detectors ----
    dt = _read("table_detectors.csv")
    if dt is not None:
        w("\n## Detectors (tuned on dev)\n")
        w(dt.round(4).to_markdown(index=False))

    # ---- concept panel ----
    cp = _read("concept_panel.csv")
    if cp is not None:
        w("\n## Concept-drift stress panel (in-regime floor trigger)\n")
        w(cp.round(4).to_markdown(index=False))
    gc = _read("gate_cadence.csv")
    if gc is not None:
        w("\n## Gate cadence (short vs long window)\n")
        w(gc.round(4).to_markdown(index=False))

    # ---- NordicDat diagnosis ----
    nd = _read("nordicdat_diagnosis.csv")
    if nd is not None:
        w("\n## NordicDat diagnosis\n")
        w(nd.to_markdown(index=False))

    with open(os.path.join(HERE, "paper_values.md"), "w") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))
    print("\nwrote paper_values.md")


if __name__ == "__main__":
    main()
