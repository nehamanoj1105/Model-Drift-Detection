#!/usr/bin/env python3
"""Assemble every result referenced in the RAPT paper plus the correct figures
into a single zip under results/extract/v3/.

Writes:
  results/extract/v3/paper_results/PAPER_RESULTS.md
  results/extract/v3/paper_results/figures/*            (figures the paper uses)
  results/extract/v3/paper_results/tables/*             (committed source tables)
  results/extract/v3/paper_results/notes/*              (reports, audit script)
  results/extract/v3/RAPT_paper_results.zip

Run from the project directory:
    python "results/extract/v3/paper_results.py"
"""
import os
import shutil
import zipfile
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
STAGE = os.path.join(HERE, "paper_results")
PREFIX = "Ensemble Learning for Model Drift Detection/"


def rel(p):
    return PREFIX + p


def md_table(df, cols=None):
    d = df if cols is None else df[cols]
    lines = ["| " + " | ".join(str(c) for c in d.columns) + " |",
             "|" + "|".join("---" for _ in d.columns) + "|"]
    for _, r in d.iterrows():
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in r.values) + " |")
    return "\n".join(lines)


def build_stage():
    for sub in ("figures", "tables", "notes"):
        os.makedirs(os.path.join(STAGE, sub), exist_ok=True)

    # ---- figures the manuscript references (paper/figures) ----
    used = ["computational_cost.png", "computational_cost.pdf",
            "rapt_ablation.png", "rapt_ablation.pdf",
            "detector_comparison.png", "detector_comparison.pdf",
            "ugr_rolling_accuracy.png"]
    for fn in used:
        src = os.path.join(ROOT, "paper", "figures", fn)
        if os.path.exists(src):
            shutil.copy2(src, os.path.join(STAGE, "figures", fn))
    # supplementary figures generated by the same committed scripts
    supp = ["primary_performance.png", "primary_performance.pdf",
            "cost_tradeoff.png", "cost_tradeoff.pdf",
            "streaming_performance.png", "three_dataset_f1.png"]
    for fn in supp:
        src = os.path.join(ROOT, "paper", "figures", fn)
        if os.path.exists(src):
            shutil.copy2(src, os.path.join(STAGE, "figures", "supplementary_" + fn))

    # ---- source tables ----
    tables = [
        ("tableII_primary_9a.csv", "experiments/exp9a/tables/table9a_main.csv"),
        ("tableII_primary_9b_nr.csv", "results/experiment_9b/natural_drift/summary.csv"),
        ("tableIII_ablation_final.csv", "Final_Experiments/results/tables/table_final_main.csv"),
        ("detectors_9a.csv", "experiments/exp9a/tables/table9a_drift_detectors.csv"),
        ("statistics_9a.csv", "experiments/exp9a/tables/statistics_9a.csv"),
        ("statistics_9b_nr.csv", "results/experiment_9b/natural_drift/statistical_tests.csv"),
        ("ablation_stats_final.csv", "Final_Experiments/results/tables/table_final_stats.csv"),
        ("revalidation_A1_summary.csv", "results/revalidation/A1_summary_all_streams.csv"),
        ("revalidation_A1_pooled.csv", "results/revalidation/A1_pooled_all_streams.csv"),
        ("revalidation_A7_wilcoxon.csv", "results/revalidation/A7_wilcoxon.csv"),
        ("revalidation_A7_tost.csv", "results/revalidation/A7_tost.csv"),
        ("revalidation_A8_label_delay.csv", "results/revalidation/A8_label_delay.csv"),
    ]
    for out, src in tables:
        sp = os.path.join(ROOT, src)
        if os.path.exists(sp):
            shutil.copy2(sp, os.path.join(STAGE, "tables", out))

    # ---- notes ----
    notes = [
        ("FINAL_EXPERIMENTS_REPORT.md", "Final_Experiments/FINAL_EXPERIMENTS_REPORT.md"),
        ("SUBMISSION_NOTES.md", "Paper_Final/SUBMISSION_NOTES.md"),
        ("EXPERIMENT_9A_THREE_TELECOM_DATASETS_REPORT.md",
         "experiments/exp9a/EXPERIMENT_9A_THREE_TELECOM_DATASETS_REPORT.md"),
        ("EXPERIMENT_9B_FINAL_REPORT.md", "EXPERIMENT_9B_FINAL_REPORT.md"),
        ("verify_paper_numbers.py", "audit/verify_paper_numbers.py"),
        ("make_paper_figures.py", "paper/make_paper_figures.py"),
        ("make_ugr_rolling_figure.py", "Paper_Final/make_ugr_rolling_figure.py"),
    ]
    for out, src in notes:
        sp = os.path.join(ROOT, src)
        if os.path.exists(sp):
            shutil.copy2(sp, os.path.join(STAGE, "notes", out))


def build_md():
    t9a = pd.read_csv(os.path.join(ROOT, "experiments", "exp9a", "tables", "table9a_main.csv"))
    t9b = pd.read_csv(os.path.join(ROOT, "results", "experiment_9b", "natural_drift", "summary.csv"))
    fin = pd.read_csv(os.path.join(ROOT, "Final_Experiments", "results", "tables", "table_final_main.csv"))
    det = pd.read_csv(os.path.join(ROOT, "experiments", "exp9a", "tables", "table9a_drift_detectors.csv"))
    st9a = pd.read_csv(os.path.join(ROOT, "experiments", "exp9a", "tables", "statistics_9a.csv"))
    st9b = pd.read_csv(os.path.join(ROOT, "results", "experiment_9b", "natural_drift", "statistical_tests.csv"))
    finst = pd.read_csv(os.path.join(ROOT, "Final_Experiments", "results", "tables", "table_final_stats.csv"))

    out = []
    A = out.append
    A("# RAPT paper — results and figures")
    A("")
    A("Paper: *When Is Reuse Safe? Regime-Aware Policy Transfer for Recurring Drift "
      "in Network Telemetry* (`paper/main.tex`, identical to "
      "`Paper_Final/manuscript.tex`).")
    A("")
    A("Every value below is copied from a committed CSV; the source path is given "
      "for each table. `audit/verify_paper_numbers.py` re-derives 205/205 of the "
      "manuscript's quantitative claims from these artefacts (0 failures).")
    A("")
    A("Contents of this archive:")
    A("- `figures/` — the four figures the manuscript includes, plus the "
      "supplementary figures produced by the same committed scripts.")
    A("- `tables/` — the committed source tables behind Table II, Table III and the "
      "statistics.")
    A("- `notes/` — the experiment reports and the figure/verification scripts.")
    A("")

    # Table II
    A("## Experiment 1 — primary comparison (manuscript Table II)")
    A("")
    A("Source: `experiments/exp9a/tables/table9a_main.csv` (Campus / UGR'16 / "
      "NordicDat) and `results/experiment_9b/natural_drift/summary.csv` (5G NR). "
      "Mean +/- sd over seeds 42-46.")
    A("")
    cols9a = ["Dataset", "Model", "Macro-F1", "Accuracy", "Precision", "Recall",
              "Adapt CPU", "Runtime", "Retrains", "Reuses"]
    A(md_table(t9a, cols=cols9a))
    A("")
    A("5G NR latency (natural drift):")
    A("")
    nr = t9b.copy()
    nr["Macro-F1"] = nr.macro_f1_mean.round(4).astype(str) + " +/- " + nr.macro_f1_std.round(4).astype(str)
    nr["Accuracy"] = nr.accuracy_mean.round(4).astype(str) + " +/- " + nr.accuracy_std.round(4).astype(str)
    nr["Adapt CPU"] = nr.adaptation_cpu_sec_mean.round(4).astype(str)
    nr["Retrains"] = nr.retrain_events_mean.round(1)
    nr["Reuses"] = nr.reused_checkpoints_mean.round(1)
    A(md_table(nr, cols=["method", "Macro-F1", "Accuracy", "Adapt CPU", "Retrains", "Reuses"]))
    A("")
    A("Figure: `figures/primary_performance.png` (supplementary; the manuscript "
      "keeps the numbers in Table II).")
    A("")

    # cost
    A("## Experiment 2 — computational cost and reuse (Fig. 3)")
    A("")
    A("Adaptation-CPU reduction of RAPT vs Full Retraining, computed from Table II:")
    A("")
    reds = []
    for ds in ["5G Campus QoS", "UGR'16", "NordicDat"]:
        fr = t9a[(t9a.Dataset == ds) & (t9a.Model == "Full Retraining")].adapt_cpu_mean.iloc[0]
        rp = t9a[(t9a.Dataset == ds) & (t9a.Model == "RAPT")].adapt_cpu_mean.iloc[0]
        reds.append((ds, fr, rp, 100 * (fr - rp) / fr))
    fr = t9b[t9b.method == "Full Retraining"].adaptation_cpu_sec_mean.iloc[0]
    rp = t9b[t9b.method == "RAPT"].adaptation_cpu_sec_mean.iloc[0]
    reds.append(("5G NR", fr, rp, 100 * (fr - rp) / fr))
    A(md_table(pd.DataFrame(reds, columns=["dataset", "FR CPU (s)", "RAPT CPU (s)",
                                           "reduction (%)"])))
    A("")
    A("Figure: `figures/computational_cost.png` (adaptation CPU, UGR'16 + NordicDat).")
    A("")

    # rolling
    A("## Experiment 3 — UGR'16 rolling accuracy (Fig. 2)")
    A("")
    A("Source: `results/experiment_9a_three/raw/per_window_ugr16_full.csv`; "
      "generator `notes/make_ugr_rolling_figure.py`. Vertical ticks are novelty "
      "refits (first appearance of each regime).")
    A("")
    A("Figure: `figures/ugr_rolling_accuracy.png`.")
    A("")

    # scatter
    A("## Experiment 4 — accuracy-cost trade-off (Fig. 4, inline TikZ)")
    A("")
    A("Coordinates are (CPU saved vs Full Retraining %, delta macro-F1) from Table II:")
    A("")
    scat = pd.DataFrame([
        dict(model="RAPT", Campus=(83.6, -0.0455), UGR16=(91.7, -0.1235),
             Nordic=(88.2, -0.0409), NR=(48.2, -0.0133)),
        dict(model="RAPT-Enhanced", Campus=(83.3, -0.0455), UGR16=(88.5, -0.0319),
             Nordic=(-20.2, -0.0444), NR=(-12.7, -0.0112)),
    ])
    A(md_table(scat))
    A("")

    # ablation
    A("## Experiment 5 — efficiency ablation on 5G Campus (Table III, Fig. 5)")
    A("")
    A("Source: `Final_Experiments/results/tables/table_final_main.csv`. The "
      "manuscript quotes Full Retrain, RAPT-Full, RAPT-Evidence, RAPT-Floor, "
      "RAPT-Cheap and RAPT-Incremental; the full ladder is in the file.")
    A("")
    A(md_table(fin, cols=["Model", "Macro-F1", "Adapt CPU (s)", "Runtime (s)",
                          "Retrains", "Reuse events", "Trees trained", "Trees reused"]))
    A("")
    A("Figure: `figures/rapt_ablation.png`.")
    A("")

    # detectors
    A("## Experiment 6 — historical detector comparison (Fig. 6)")
    A("")
    A("Source: `experiments/exp9a/tables/table9a_drift_detectors.csv`.")
    A("")
    A(md_table(det, cols=["Dataset", "Method", "Macro-F1", "Adapt CPU",
                          "Runtime", "Adaptation Events"]))
    A("")
    A("ADWIN, Page-Hinkley and EDMA never fire on any stream; EDD fires 38 "
      "(Campus), 39 (UGR'16), 39 (NordicDat) times. Figure: "
      "`figures/detector_comparison.png`.")
    A("")

    # statistics
    A("## Experiment 7 — statistical tests")
    A("")
    A("### 9A window-level Wilcoxon + Cohen's d (Campus / UGR'16 / NordicDat)")
    A("")
    A(md_table(st9a))
    A("")
    A("### 5G NR window-level Wilcoxon")
    A("")
    A(md_table(st9b))
    A("")
    A("### Ablation seed-level comparison vs Full Retraining (5G Campus)")
    A("")
    A(md_table(finst))
    A("")

    # cost drivers
    A("## Experiment 8 — refit cost drivers (micro-benchmarks)")
    A("")
    A("Source: `notes/FINAL_EXPERIMENTS_REPORT.md` section 4.")
    A("")
    A("| Factor | Setting | Cost per refit |")
    A("|---|---|---|")
    A("| n_estimators | 20 trees (10 RF + 10 ET) | 22 ms |")
    A("| | 50 trees | 54 ms |")
    A("| | 100 trees (full) | 104 ms |")
    A("| Buffer size | 200 samples | 80 ms |")
    A("| | 500 | 92 ms |")
    A("| | 1000 (full) | 104 ms |")
    A("")

    # revalidation
    A("## Experiment 9 — independent re-validation")
    A("")
    A("Source: `results/revalidation/` (A1 reproduction, A7 tests, A8 label "
      "delay). `tables/revalidation_A1_summary.csv` reproduces the Table II "
      "predictive metrics; the adaptation CPU re-run shifts by up to 0.14 s but "
      "the ordering and savings are stable.")
    A("")
    A("`notes/verify_paper_numbers.py` re-derives every claim from the committed "
      "artefacts: 205 checks, 0 failures.")
    A("")

    with open(os.path.join(STAGE, "PAPER_RESULTS.md"), "w") as f:
        f.write("\n".join(out) + "\n")


def make_zip():
    zpath = os.path.join(HERE, "RAPT_paper_results.zip")
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for root, _, files in os.walk(STAGE):
            for fn in files:
                fp = os.path.join(root, fn)
                arc = os.path.relpath(fp, os.path.dirname(STAGE))
                z.write(fp, arc)
    print("wrote", zpath, os.path.getsize(zpath), "bytes")
    return zpath


if __name__ == "__main__":
    build_stage()
    build_md()
    make_zip()
