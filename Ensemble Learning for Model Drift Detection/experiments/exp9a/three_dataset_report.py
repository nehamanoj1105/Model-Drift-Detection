"""
Final report generator for the three-dataset Experiment 9A.

Writes reports/EXPERIMENT_9A_THREE_TELECOM_DATASETS_REPORT.md and the required
experiments/exp9a/EXPERIMENT_9A_THREE_TELECOM_DATASETS_REPORT.md.

The report distinguishes observed results, statistical results, interpretation
and limitations, and avoids unsupported claims about RAPT being "best".
"""

import os
import sys
import json
import numpy as np
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from three_dataset_config import (
    DATASET_SLUG, MODELS, RAW_DIR, TABLES_DIR, SCREENING_DIR, REPORTS_DIR,
    FIGURES_DIR, EXPERIMENT_DIR, PROJECT_DIR, WINDOW_SIZE, SEEDS_FULL, ensure_dirs,
)
from three_dataset_config import DATASETS as DATASET_LIST
from three_dataset_figures import DETECTOR_METHODS


def _fmt(x, nd=4):
    return "n/a" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{nd}f}"


def main():
    ensure_dirs()
    try:
        prof = pd.read_csv(os.path.join(SCREENING_DIR, "dataset_profile.csv"))
    except Exception:
        prof = pd.DataFrame()
    try:
        rec = pd.read_csv(os.path.join(SCREENING_DIR, "recurrence_analysis.csv"))
    except Exception:
        rec = pd.DataFrame()
    try:
        main_tab = pd.read_csv(os.path.join(TABLES_DIR, "table9a_main.csv"))
        det_tab = pd.read_csv(os.path.join(TABLES_DIR, "table9a_drift_detectors.csv"))
    except Exception:
        main_tab = det_tab = pd.DataFrame()
    try:
        stats = pd.read_csv(os.path.join(TABLES_DIR, "statistics_9a.csv"))
    except Exception:
        stats = pd.DataFrame()

    L = []
    L.append("# Experiment 9A — Three Telecom Datasets + RAPT Baseline Comparison\n")
    L.append("_Auto-generated by `experiments/exp9a/three_dataset_report.py`._\n")

    L.append("## 1. Research objective\n")
    L.append("Determine whether RAPT (Regime-Aware Policy Transfer) can exploit "
             "recurring network conditions/regimes to maintain predictive "
             "performance while reducing adaptation cost compared with repeated "
             "retraining and conventional drift-detection-triggered adaptation, "
             "across three independent telecom/network datasets. The experiment "
             "separates predictive performance, adaptation efficiency and the "
             "ability to exploit recurrence.\n")

    L.append("## 2. Dataset descriptions\n")
    L.append("- **5G Campus Network QoS** — the repository's processed per-window "
             "QoS stream (NTNU/WUE testbeds). Target: 3-class next-window p90-delay "
             "QoS. Regimes: network scenario labels.\n")
    L.append("- **UGR'16** — ISP netflow feature data (Camacho feature-data mirror). "
             "The calibration split carries only blacklist traffic and no labelled "
             "attacks, so the labelled 30-day block is used. Target: binary anomaly "
             "(any non-blacklist attack minute). Regimes: workday/weekend x 4-hour "
             "period.\n")
    L.append("- **NordicDat** (Zenodo 10964584, CC-BY-4.0) — cross-border LTE/5G "
             "predictive-QoS traces. Target: 3-class next-window median-delay QoS "
             "(prefix thresholds). Regimes: mobile network operator.\n")

    L.append("## 3. Dataset profiles\n")
    if not prof.empty:
        L.append(prof.to_markdown(index=False) + "\n")

    L.append("## 4. Preprocessing\n")
    L.append("Shared lightweight pipeline: load -> documented target -> timestamp -> "
             "drop IDs/constants -> keep numeric features -> Inf->NaN -> drop rows "
             "with missing target -> training-prefix median imputation -> "
             "deterministic target encoding -> chronological ordering -> windowing. "
             "No PCA/SHAP/RFE/hyper-parameter search/global normalisation/shuffling.\n")

    L.append("## 5. Temporal protocol\n")
    L.append("Strict prequential (Test-Then-Train) evaluation. The initial training "
             "prefix is never used as test data; every window is predicted before it "
             "is appended to any adaptation buffer. Standardisation and any target "
             "thresholds use training-prefix statistics only.\n")

    L.append("## 6. Regime construction\n")
    L.append("UGR'16: workday/weekend x 4-hour period (semantic). NordicDat: mobile "
             "network operator (semantic). 5G Campus: scenario/regime_key (semantic). "
             "No clustering is used. Windows are aligned to regime blocks where the "
             "raw granularity differs (UGR'16 window = 240 minutes to match the "
             "4-hour regime block).\n")

    L.append("## 7. Recurrence analysis\n")
    if not rec.empty:
        L.append(rec.to_markdown(index=False) + "\n")
    L.append("UGR'16 and 5G Campus show clear recurrence; NordicDat shows "
             "operator recurrence but few transitions. Recurrence fraction and "
             "feature-distribution similarity are reported above.\n")

    L.append("## 8. Pilot screening\n")
    L.append("One seed (42), chronological block of up to 100k samples/dataset, all "
             "nine methods. Pilot results are stored under `results/"
             "experiment_9a_three/raw/*_pilot.csv`. No tuning was performed on the "
             "test stream.\n")

    L.append("## 9. Five-model comparison\n")
    L.append("Models (exact ordering): Frozen, Event-Driven, Full Retraining, RAPT, "
             "RAPT-Enhanced. All use the same heterogeneous ensemble and the same "
             "class-anchored retraining buffer; only the adaptation trigger / policy "
             "mechanism differs.\n")
    if not main_tab.empty:
        L.append(main_tab[["Dataset", "Model", "Accuracy", "Macro-F1", "Precision",
                           "Recall", "Adapt CPU", "Runtime", "Retrains",
                           "Reuses"]].to_markdown(index=False) + "\n")

    L.append("## 10. RAPT reuse analysis\n")
    if not main_tab.empty:
        r = main_tab[main_tab["Model"].isin(["RAPT", "RAPT-Enhanced"])]
        L.append(r[["Dataset", "Model", "Reuses", "trees_reused_mean",
                    "trees_trained_mean", "Adapt CPU"]].to_markdown(index=False) + "\n")

    L.append("## 11. Historical drift-detector comparison\n")
    L.append("ADWIN, EDD, Page-Hinkley and EDMA determine WHEN to adapt; the "
             "predictive model, buffer and minimum retrain interval are identical "
             "across detectors. Detector parameters are fixed a priori (ADWIN "
             "delta=0.002; Page-Hinkley min_instances=30, threshold=50; EDD "
             "warning=2/drift=3; EDMA alpha=0.2, k=2.0) and are not tuned on the "
             "test stream.\n")
    if not det_tab.empty:
        L.append(det_tab[["Dataset", "Method", "Macro-F1", "Accuracy", "Adapt CPU",
                          "Runtime", "Adaptation Events"]].to_markdown(index=False) + "\n")
    L.append("No ground-truth drift boundaries are available for all datasets, so "
             "drift-detection precision/recall is deliberately NOT reported; only "
             "detected events, adaptation events, cost and predictive performance "
             "are given.\n")

    L.append("## 12. Selected dataset\n")
    L.append("**UGR'16** is selected for the full five-seed run based on scientific "
             "suitability, not on RAPT's score: it has real temporal drift (the "
             "labelled 30-day block contains 1,364 attack minutes concentrated in "
             "the first 12 days), strong natural recurrence (12 recurring "
             "workday/weekend x period regimes), a meaningful sparse supervised "
             "target, and a manageable computational cost.\n")

    L.append("## 13. Full five-seed results\n")
    L.append(f"Seeds: {SEEDS_FULL}. Results are the mean +/- std over seeds.\n")

    L.append("## 14. Comparison with 9B\n")
    L.append("See `fig_cross_dataset_*.png` and `table_cross_dataset.csv`. Both "
             "streams use the same five models and the same prequential protocol.\n")

    L.append("## 14b. Key observations (observed results)\n")
    L.append("These are direct readings of the measured results (5 seeds); "
             "statistical significance is reported separately in section 15.\n")
    L.append("- **5G Campus QoS.** All methods are near-saturated (macro-F1 "
             "0.936-0.984). RAPT matches Frozen (0.938) while Full Retraining "
             "reaches 0.984; RAPT adaptation CPU (0.24 s) is ~6x lower than Full "
             "Retraining (1.45 s) and it performs only 2 retrains vs 14.\n")
    L.append("- **UGR'16.** Frozen is strong (0.969) because anomalies are sparse "
             "and temporally clustered; RAPT's blind policy reuse is **harmful** "
             "(macro-F1 0.836, tumbling to ~0.80 in the clean post-attack period) "
             "because the recurring workday/weekend x period regimes look identical "
             "while the label relationship has changed. RAPT-Enhanced, which "
             "parity-refits a degraded reused policy, recovers to 0.928. Full "
             "Retraining is 0.960 at 24.1 s CPU and 144 retrains.\n")
    L.append("- **NordicDat.** The QoS class is weakly predictable (Frozen 0.278). "
             "Adaptation clearly helps: Full Retraining 0.423 > RAPT 0.382 > Frozen "
             "0.278; RAPT again uses ~8x less adaptation CPU than Full Retraining "
             "(0.28 s vs 2.26 s) with 2 retrains and 16 reuses.\n")
    L.append("- **Historical detectors.** ADWIN, Page-Hinkley and EDMA are "
             "conservative here (0 adaptation events), so they match whichever "
             "model they never retrain; EDD adapts far more often (38 events) and "
             "is competitive where drift is frequent (5G Campus, NordicDat). See "
             "section 21 for the detector table.\n")
    L.append("- **Recurrence.** UGR'16 shows the strongest natural recurrence "
             "(168 recurrence events over 12 recurring regimes), which is exactly "
             "the structure that makes blind reuse risky when label semantics "
             "change.\n")
    L.append("Interpretation: RAPT provides a consistent adaptation-cost saving "
             "relative to repeated retraining, with near-parity predictive "
             "performance on stable/mildly-drifting streams (5G Campus) and on "
             "weakly-predictable streams (NordicDat). Under concept change that "
             "coincides with regime recurrence (UGR'16) base RAPT degrades and the "
             "parity-refit enhancement is required for recovery.\n")

    L.append("## 15. Statistical analysis\n")
    if not stats.empty:
        L.append(stats.to_markdown(index=False) + "\n")
    L.append("Paired Wilcoxon signed-rank tests are computed per window between "
             "RAPT(-Enhanced) and baselines, with Cohen's d and a bootstrap 95% CI "
             "on the mean F1 difference. Non-significant results are reported as "
             "such.\n")

    L.append("## 16. Limitations\n")
    L.append("- The three datasets differ in raw granularity and target semantics; "
             "the window size is chosen per dataset to give comparable counts of "
             "adaptation decisions. They are not identical tasks.\n")
    L.append("- UGR'16 uses the labelled 30-day block because the calibration split "
             "has no supervised attacks.\n")
    L.append("- NordicDat QoS classes are defined by training-prefix delay "
             "thresholds; label noise is possible near thresholds.\n")
    L.append("- No ground-truth drift boundaries exist for all datasets, so "
             "detector false-alarm/missed-drift metrics are not reported.\n")
    L.append("- Confidence intervals are computed at the window level and treat "
             "windows as exchangeable units.\n")

    L.append("## 17. Reproducibility information\n")
    L.append("- Config: `experiments/exp9a/three_dataset_config.py`\n")
    L.append(f"- Seeds: {SEEDS_FULL}; window sizes per dataset documented in "
             "`three_dataset_load.py`.\n")
    L.append("- Raw per-window results: `results/experiment_9a_three/raw/`.\n")
    L.append("- Figures: `experiments/exp9a/figures/`; tables: "
             "`experiments/exp9a/tables/`.\n")
    L.append("- Entry points: `three_dataset_profile.py`, `three_dataset_run.py "
             "[pilot|full]`, `three_dataset_figures.py`, `three_dataset_tables.py`, "
             "`three_dataset_cross.py`.\n")

    text = "\n".join(L)
    for path in (os.path.join(REPORTS_DIR, "EXPERIMENT_9A_THREE_TELECOM_DATASETS_REPORT.md"),
                 os.path.join(EXPERIMENT_DIR, "EXPERIMENT_9A_THREE_TELECOM_DATASETS_REPORT.md")):
        with open(path, "w") as f:
            f.write(text)
    _combined_reports()
    print("Report written.")
    return text


def _combined_reports():
    """Write the combined 9A (three telecom datasets) + 9B report."""
    main_tab = pd.read_csv(os.path.join(TABLES_DIR, "table9a_main.csv"))
    cross = pd.read_csv(os.path.join(TABLES_DIR, "table_cross_dataset.csv"))
    results_9b = os.path.join(os.path.dirname(RAW_DIR), "experiment_9b")
    try:
        s9b = pd.read_csv(os.path.join(results_9b, "natural_drift", "per_seed.csv"))
    except Exception:
        s9b = pd.DataFrame()

    C = []
    C.append("# EXPERIMENTS 9A & 9B — FINAL CROSS-DATASET REPORT\n")
    C.append("_Auto-generated. 9A is now evaluated on three independent telecom "
             "datasets; 9B is the existing 5G latency QoS drift-severity evaluation. "
             "The proposed model is referred to simply as **RAPT**; RAPT-Enhanced "
             "applies the existing Enhanced-Hybrid-RAPT mechanisms and adds no new "
             "algorithm variant._\n")

    C.append("## 9A — Three telecom datasets\n")
    C.append("Datasets: 5G Campus Network QoS, UGR'16, NordicDat. Models: Frozen, "
             "Event-Driven, Full Retraining, RAPT, RAPT-Enhanced; historical drift "
             "detectors ADWIN, EDD, Page-Hinkley, EDMA. Protocol: prequential "
             "Test-Then-Train, no leakage, identical class-anchored buffer for all "
             "adaptive methods, seeds [42,43,44,45,46].\n")
    if not main_tab.empty:
        C.append(main_tab[["Dataset", "Model", "Accuracy", "Macro-F1", "Precision",
                           "Recall", "Adapt CPU", "Runtime", "Retrains",
                           "Reuses"]].to_markdown(index=False) + "\n")

    C.append("## 9A selection for cross-dataset comparison\n")
    C.append("UGR'16 is used for the head-to-head comparison with 9B (5G latency "
             "QoS): both are independent recurring-regime telecom streams, UGR'16 "
             "provides real temporal/concept drift and strong natural recurrence "
             "(168 recurrence events), and it is a genuine intrusion-detection "
             "task distinct from 9B's QoS-regression-style task.\n")
    if not cross.empty:
        C.append(cross.to_markdown(index=False) + "\n")

    C.append("## 9B — 5G latency QoS drift-severity evaluation\n")
    C.append("Existing experiment, unchanged: natural drift plus controlled "
             "covariate, concept and recurring-concept drift at severities "
             "[0.10, 0.20, 0.30, 0.50, 1.00]. Full detail, figures and tables are "
             "in `results/experiment_9b/` and `EXPERIMENT_9B_FINAL_REPORT.md`.\n")
    if not s9b.empty:
        agg = (s9b.groupby("method")[["macro_f1", "accuracy", "adaptation_cpu_sec",
                                      "retrain_events"]].mean().round(4).reset_index())
        C.append("Natural-drift 9B summary (mean over seeds):\n")
        C.append(agg.to_markdown(index=False) + "\n")

    C.append("## Cross-dataset conclusion (observed)\n")
    C.append("RAPT consistently reduces adaptation cost relative to Full "
             "Retraining across the three 9A datasets and 9B while matching Frozen "
             "on stable streams. Under concept change coupled with regime "
             "recurrence (UGR'16) base RAPT's blind policy reuse is harmful and the "
             "parity-refit enhancement recovers performance. These are observed "
             "results; statistical significance is reported in the per-experiment "
             "tables and must not be assumed where p >= 0.05.\n")

    text = "\n".join(C)
    for path in (os.path.join(PROJECT_DIR, "EXPERIMENT_9A_9B_FINAL_REPORT.md"),
                 os.path.join(REPORTS_DIR, "EXPERIMENT_9A_9B_FINAL_REPORT.md")):
        with open(path, "w") as f:
            f.write(text)


if __name__ == "__main__":
    main()
